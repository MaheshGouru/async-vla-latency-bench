#!/usr/bin/env python3
"""Fail-closed audit for the official VLASH integration."""
import argparse, json, subprocess
from pathlib import Path

OFFICIAL_REPOSITORY = "https://github.com/mit-han-lab/vlash"


def git(path, *args):
    return subprocess.run(["git", "-C", str(path), *args], capture_output=True, text=True).stdout.strip()


def main():
    p=argparse.ArgumentParser()
    p.add_argument("--vlash-checkout", type=Path, required=True)
    p.add_argument("--vlash-checkpoint", type=Path, required=True)
    p.add_argument("--output", type=Path, required=True)
    p.add_argument("--expected-revision", required=True)
    p.add_argument("--semantic-attestation", type=Path)
    args=p.parse_args()
    checks={}
    checks["official_repository"] = git(args.vlash_checkout,"remote","get-url","origin").rstrip(".git") == OFFICIAL_REPOSITORY
    revision=git(args.vlash_checkout,"rev-parse","HEAD")
    checks["immutable_revision"] = revision == args.expected_revision and len(revision)==40
    pyproject=args.vlash_checkout/"pyproject.toml"
    train=args.vlash_checkout/"examples/train/pi05/async.yaml"
    inference=args.vlash_checkout/"examples/inference/async.yaml"
    text=pyproject.read_text() if pyproject.exists() else ""
    train_text=train.read_text() if train.exists() else ""
    inference_text=inference.read_text() if inference.exists() else ""
    checks["official_pi05_support"] = "type: pi05" in train_text
    checks["future_state_training_declared"] = "state_cond: true" in train_text and "max_delay_steps:" in train_text
    checks["async_inference_declared"] = "inference_overlap_steps:" in inference_text
    checks["checkpoint_exists"] = args.vlash_checkpoint.exists()
    # These scientific matches require adapter tests and are never inferred
    # merely from package installation. The attestation is generated by those
    # tests; this audit does not provide a command-line bypass for individual
    # booleans.
    semantic_names=("libero_observation_action_semantics", "control_frequency_20hz",
                    "normalization_matches_stage1", "prediction_execution_semantics_h25",
                    "native_plus_200ms_latency_semantics", "episode_identity_provenance_hooks")
    attestation={}
    if args.semantic_attestation and args.semantic_attestation.exists():
        attestation=json.loads(args.semantic_attestation.read_text())
    checks["semantic_attestation_bound_to_revision"] = (
        attestation.get("vlash_revision") == revision
        and attestation.get("vlash_checkpoint") == str(args.vlash_checkpoint)
    )
    for name in semantic_names:
        checks[name] = attestation.get("checks",{}).get(name) is True
    report={
        "status":"PASS" if all(checks.values()) else "FAIL",
        "official_repository":OFFICIAL_REPOSITORY,
        "vlash_revision":revision,
        "expected_revision":args.expected_revision,
        "vlash_checkpoint":str(args.vlash_checkpoint),
        "semantic_attestation":str(args.semantic_attestation) if args.semantic_attestation else "",
        "checks":checks,
        "blocking_reasons":[name for name,value in checks.items() if not value],
        "source_notes":{
            "training":"Official PI05 async config uses state_cond=true and delay-conditioned fine-tuning.",
            "inference":"Official async config expects a trained checkpoint and inference_overlap_steps.",
            "policy":"Do not substitute an approximate async implementation for official VLASH.",
        },
    }
    payload=json.dumps(report,indent=2,sort_keys=True)+"\n"
    args.output.parent.mkdir(parents=True,exist_ok=True); args.output.write_text(payload)
    print(report["status"], "Stage 4 VLASH compatibility gate")
    if report["blocking_reasons"]: print("BLOCKED:", ", ".join(report["blocking_reasons"]))
    return 0 if report["status"]=="PASS" else 2


if __name__=="__main__": raise SystemExit(main())
